import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { normalizeUsdaFoundationFoods } from "../src/services/usda-food-import-service.ts";

const projectRoot = resolve(import.meta.dirname, "..");
const inputPath = resolve(process.argv[2] ?? `${projectRoot}/data/usda/FoodData_Central_foundation_food_json_2026-04-30.json`);
const outputPath = resolve(process.argv[3] ?? `${projectRoot}/src/data/usdaFoundationFoods.ts`);
const source: unknown = JSON.parse(await readFile(inputPath, "utf8"));
const result = normalizeUsdaFoundationFoods(source);
const generated = [
  "// Generated by scripts/import-usda-foundation-foods.ts. Do not edit by hand.",
  'import type { Food } from "@/types";',
  "",
  `export const usdaFoundationFoods: Food[] = ${JSON.stringify(result.foods, null, 2)};`,
  "",
  `export const usdaFoundationImportSummary = ${JSON.stringify(result.report, null, 2)} as const;`,
  "",
].join("\n");

await writeFile(outputPath, generated, "utf8");
console.log(JSON.stringify({ input: inputPath, output: outputPath, ...result.report }, null, 2));