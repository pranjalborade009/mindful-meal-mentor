import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { FNDDS_SELECTED_FDC_IDS, normalizeFnddsFoods } from "../src/services/fndds-food-import-service.ts";

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function sourceFoodId(value: unknown): number | null {
  if (!isRecord(value)) return null;
  const id = value["fdcId"];
  return typeof id === "number" && Number.isInteger(id) && id > 0 ? id : null;
}

const projectRoot = resolve(import.meta.dirname, "..");
const inputPath = resolve(process.argv[2] ?? `${projectRoot}/data/usda/FNDDS_2021-2023_indian-dishes.json`);
const rawSnapshotPath = resolve(`${projectRoot}/data/usda/FNDDS_2021-2023_indian-dishes.json`);
const outputPath = resolve(process.argv[3] ?? `${projectRoot}/src/data/usdaFnddsFoods.ts`);
const source: unknown = JSON.parse(await readFile(inputPath, "utf8"));
const sourceFoods = Array.isArray(source)
  ? source
  : isRecord(source) && Array.isArray(source["SurveyFoods"])
    ? source["SurveyFoods"]
    : null;

if (!sourceFoods) throw new TypeError("Expected a USDA FNDDS SurveyFoods JSON dataset.");

const selectedIds = new Set<number>(FNDDS_SELECTED_FDC_IDS);
const selectedRecords = sourceFoods.filter((record) => {
  const id = sourceFoodId(record);
  return id !== null && selectedIds.has(id);
});
const foundIds = new Set(selectedRecords.map(sourceFoodId).filter((id): id is number => id !== null));
const missingIds = FNDDS_SELECTED_FDC_IDS.filter((id) => !foundIds.has(id));
if (missingIds.length) throw new Error(`FNDDS source is missing selected FDC IDs: ${missingIds.join(", ")}`);

const rawSnapshot = { SurveyFoods: selectedRecords };
if (inputPath !== rawSnapshotPath) await writeFile(rawSnapshotPath, JSON.stringify(rawSnapshot, null, 2), "utf8");
const result = normalizeFnddsFoods(rawSnapshot);
if (result.report.validFoodCount !== FNDDS_SELECTED_FDC_IDS.length || result.report.unavailableSelectedIds.length) {
  throw new Error(`FNDDS import validation failed: ${JSON.stringify(result.report)}`);
}

const generated = [
  "// Generated by scripts/import-usda-fndds-foods.ts. Do not edit by hand.",
  'import type { Food } from "@/types";',
  "",
  `export const usdaFnddsFoods: Food[] = ${JSON.stringify(result.foods, null, 2)};`,
  "",
  `export const usdaFnddsImportSummary = ${JSON.stringify(result.report, null, 2)} as const;`,
  "",
].join("\n");

await writeFile(outputPath, generated, "utf8");
console.log(JSON.stringify({ input: inputPath, rawSnapshot: rawSnapshotPath, output: outputPath, ...result.report }, null, 2));